def main():
    rows = parse_bestiary()
    assert len(rows) == 204, f"Expected 204 bestiary rows, parsed {len(rows)}"
    specs = build_specs(rows)
    ids = [s["id"] for s in specs]
    assert len(set(ids)) == 204, "Duplicate species ids in mutation table!"

    # Every theme must be represented (directive: 8 groups, none empty).
    themes = {s["theme"] for s in specs}
    assert themes == set(THEMES), f"Theme coverage gap: {set(THEMES) - themes}"

    # Attachment mask sanity: never zero, never all-bits.
    for s in specs:
        assert 0 < s["mask"] <= 0x7F, f"Bad mask {s['mask']} for {s['id']}"
        for v in (s["head"], s["torso"], s["limb"], s["tail"]):
            assert 0.7 <= v <= 1.5, f"Scale out of range for {s['id']}: {v}"

    counts = {}
    for s in specs:
        counts[s["theme"]] = counts.get(s["theme"], 0) + 1
    print(f"[sci-fantasy] {len(specs)} specs across {len(counts)} themes: {counts}")

    cpp = emit_cpp(specs)
    with open(CPP_OUT, "w", encoding="utf-8") as f:
        f.write(cpp)
    print(f"Wrote {CPP_OUT} ({len(cpp.splitlines())} lines)")

    doc = emit_doc(specs)
    with open(DOC_OUT, "w", encoding="utf-8") as f:
        f.write(doc)
    print(f"Wrote {DOC_OUT} ({len(doc.splitlines())} lines)")


if __name__ == "__main__":
    main()
