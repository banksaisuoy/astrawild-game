def spec_hash(name: str) -> int:
    h = 2166136261
    for ch in name:
        h = (h * 16777619) ^ ord(ch)
    return h & 0x7FFFFFFF


def jitter(seed: int, salt: int, spread: float, lo: float) -> float:
    v = ((seed >> (salt * 7)) % 1024) / 1023.0
    return lo + v * spread


def clamp01(c):
    return tuple(max(0.0, min(1.0, float(x))) for x in c)


# ---------------------------------------------------------------------------
# Parse the actual bestiary table (same provenance pattern as gen_tier_b.py).
# ---------------------------------------------------------------------------
def parse_bestiary() -> list:
    with open(BESTIARY, encoding="utf-8") as fh:
        src = fh.read()
    rows = re.findall(
        r'\{ TEXT\("(Echo_\w+)"\), TEXT\("(\w+)"\),\s*'
        r'EAstrawildEchoFamily::(\w+), EAstrawildBodyPlan::(\w+), EAstrawildSizeClass::(\w+),\s*'
        r'EAstrawildElementType::(\w+), EAstrawildElementType::(\w+),',
        src)
    out = []
    for (rid, name, fam, plan, size, elem, weak) in rows:
        out.append({
            "id": rid, "name": name, "family": fam, "plan": plan,
            "size": size, "element": elem, "weakness": weak,
        })
    return out


# ---------------------------------------------------------------------------
# Theme assignment (deterministic, priority-ordered).
# ---------------------------------------------------------------------------
def assign_theme(row: dict) -> str:
    name = row["name"].lower()
    fam = row["family"]
    plan = row["plan"].lower()

    # 1) strong name keywords (priority order matters).
    for theme in ("VoidAbomination", "MechanicalHybrid", "AncientConstruct",
                  "PlantMonster", "EtherealSpirit", "ElementalBeast", "ArmoredOrganic"):
        for kw in KEYWORDS[theme]:
            if kw in name:
                return theme

    # 2) body-plan overrides: amorphous blobs twist into Void unless they are
    #    flora/spirits; crystalline shards read as ancient constructs.
    if plan == "amorphous" and fam not in ("Flora", "Spirit"):
        return "VoidAbomination"
    if plan == "crystalline":
        return "AncientConstruct"

    # 3) family default.
    return FAMILY_DEFAULT.get(fam, "MutatedFauna")


def assign_base(theme: str, plan: str) -> str:
    bucket = PLAN_BUCKET.get(plan, "primary")
    return BASES[theme][bucket]


def assign_material(theme: str, plan: str) -> str:
    if plan.lower() == "crystalline":
        return CRYSTAL_OVERRIDE
    if theme == "VoidAbomination" and plan.lower() == "amorphous":
        return VOID_MATERIAL
    return MATERIAL_THEME[theme]


def assign_vfx(element: str, theme: str) -> str:
    if element in ELEMENT_VFX:
        return ELEMENT_VFX[element]
    if theme == "VoidAbomination":
        return "Void"
    return "None"


def assign_attachments(theme: str, plan: str, seed: int) -> int:
    bias = ATTACH_BIAS[theme]
    count = 1 + (seed % 3)  # 1..3 deterministic attachments
    mask = 0
    for i in range(count):
        pick = bias[(seed >> (4 + i * 3)) % len(bias)]
        mask |= ATTACH_BITS[pick]
    # Flight-capable bodies earn wings more often; ground bodies never get
    # wings from the bias alone (directive: "ปีกเกิน" is a mutant signature).
    if plan.lower() in ("avian", "floating", "serpent") and (seed % 4 == 0):
        mask |= ATTACH_BITS["Wings"]
    return mask


def assign_scales(seed: int):
    # Per-part scale multipliers in [0.75, 1.45] (deterministic per species).
    head = jitter(seed, 1, 0.70, 0.75)
    torso = jitter(seed, 2, 0.60, 0.80)
    limb = jitter(seed, 3, 0.55, 0.80)
    tail = jitter(seed, 4, 0.65, 0.70)
    return round(head, 3), round(torso, 3), round(limb, 3), round(tail, 3)


def assign_pattern_tint(theme: str, seed: int):
    base = THEME_TINTS[theme]
    r = clamp01((base[0] + jitter(seed, 5, 0.24, -0.12),))
    g = clamp01((base[1] + jitter(seed, 6, 0.24, -0.12),))
    b = clamp01((base[2] + jitter(seed, 7, 0.24, -0.12),))
    return r[0], g[0], b[0]


def build_specs(rows: list) -> list:
    specs = []
    for row in rows:
        theme = assign_theme(row)
        plan = row["plan"].lower()
        seed = spec_hash(row["name"])
        head, torso, limb, tail = assign_scales(seed)
        mask = assign_attachments(theme, plan, seed)
        tint = assign_pattern_tint(theme, seed)
        specs.append({
            "id": row["id"], "theme": theme,
            "base": assign_base(theme, plan),
            "head": head, "torso": torso, "limb": limb, "tail": tail,
            "mask": mask,
            "material": assign_material(theme, plan),
            "tint": tint,
            "vfx": assign_vfx(row["element"], theme),
            "sound": "SFXSet_" + theme,
            "family": row["family"], "plan": plan, "element": row["element"],
        })
    return specs


